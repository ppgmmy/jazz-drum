export type DrumVoice = "ride" | "hihat" | "snare" | "kick";

export type ChartLevel = "入門" | "進階" | "挑戰";

/** 一格：空、普通擊、重音、ghost */
export type Cell = "" | "x" | "X" | "g";

export type ChartPattern = {
  /** 小節數 */
  bars: number;
  /** 每拍細分（4=十六分感用 4 格/拍；swing 八分用 2） */
  perBeat: 2 | 3 | 4;
  /** 每小節拍數 */
  beatsPerBar: number;
  voices: Record<DrumVoice, Cell[]>;
};

export type DrumChart = {
  slug: string;
  title: string;
  artist: string;
  style: string;
  meter: string;
  tempo: string;
  level: ChartLevel;
  summary: string;
  focus: string[];
  pattern: ChartPattern;
};

